"""Markdown generation for MkDocs.

Layout (one canonical page per paper; every other page only links to it):

    papers/{id}-{slug}.md        canonical paper page
    {venue}/index.md             venue overview (region x year matrix)
    {venue}/{region}.md          papers of one region, grouped by year
    {venue}/by-year.md           all papers of the venue by year
    {venue}/by-topic.md          all papers of the venue by topic (category)
    videos/{id}.md, videos/index.md
    index.md                     home

The `nav:` block of mkdocs.yml is regenerated between NAV_BEGIN / NAV_END so the
sidebar shows the hierarchy instead of hundreds of paper pages.
"""
from __future__ import annotations

import logging
import re
import unicodedata
from collections import Counter, defaultdict
from pathlib import Path

import yaml

from . import config
from .database import Database
from .schemas import CATEGORIES, Resource, ResourceLink, VideoLink

log = logging.getLogger(__name__)

GENERATED_MARK = "<!-- generated by yt-paper; edits will be overwritten -->"
NAV_BEGIN = "# >>> nav (generated by yt-paper)"
NAV_END = "# <<< nav"
VENUE_ORDER = ("DVCon", "DATE", "IEEE", "arXiv")
OTHERS = "Others"
REGION_ORDER = ("US", "Europe", "India", "Japan", "China", "Taiwan")


class GeneratorError(RuntimeError):
    pass


def slugify(text: str, max_len: int = 60) -> str:
    text = unicodedata.normalize("NFKC", text).lower()
    text = re.sub(r"[^\w\s-]", "", text, flags=re.UNICODE)
    text = re.sub(r"[\s_-]+", "-", text).strip("-")
    return text[:max_len].rstrip("-") or "untitled"


def _seconds(note: str | None) -> int | None:
    """'04:15' / '1:02:03' / '255' -> seconds, else None."""
    if not note:
        return None
    m = re.search(r"\b(?:(\d+):)?(\d{1,2}):(\d{2})\b", note)
    if m:
        h, mi, s = int(m.group(1) or 0), int(m.group(2)), int(m.group(3))
        return h * 3600 + mi * 60 + s
    return int(note) if note.strip().isdigit() else None


def _embed(link: VideoLink) -> str:
    v = link.video
    start = _seconds(link.timestamp_note)
    src = f"https://www.youtube-nocookie.com/embed/{v.video_id}" + (f"?start={start}" if start else "")
    title = (v.video_title or v.video_id).replace('"', "&quot;")
    caption = f"**{v.video_title or v.video_id}**"
    if link.timestamp_note:
        caption += f" · {'⏱' if start is not None else '📝'} {link.timestamp_note}"
    return (
        f'<div class="video-wrapper"><iframe src="{src}" title="{title}" loading="lazy" '
        'allow="accelerometer; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share" '
        'referrerpolicy="strict-origin-when-cross-origin" allowfullscreen></iframe></div>\n\n'
        f"{caption} — [Watch on YouTube]({v.video_url})"
    )


def _write(path: Path, text: str) -> None:
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    except OSError as e:
        raise GeneratorError(f"파일 쓰기 실패: {path} ({e})") from e


def _frontmatter(meta: dict) -> str:
    return "---\n" + yaml.safe_dump(meta, allow_unicode=True, sort_keys=False, width=1000) + "---\n\n"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _table(header: str, rows: list[str]) -> str:
    cols = header.count("|") - 1
    return header + "\n" + "|---" * cols + "|\n" + "\n".join(rows) + "\n"


# --- bilingual layout ----------------------------------------------------------

_MERMAID_RE = re.compile(r"```mermaid\n.*?```", re.S)


def _blocks(md: str) -> list[str]:
    """Split Markdown into paragraph-level blocks (a heading, a paragraph, a whole list, a fenced block)."""
    blocks, cur, fence = [], [], False
    for line in md.strip().splitlines():
        if line.startswith("```"):
            fence = not fence
        is_item = bool(re.match(r"\s*([-*+]|\d+[.)])\s", line))
        if not fence and (not line.strip() or line.startswith("#")):
            if cur:
                blocks.append("\n".join(cur))
                cur = []
            if line.startswith("#"):
                blocks.append(line)
            continue
        top_item = is_item and not line.startswith((" ", "\t"))
        prev_item = bool(cur) and bool(re.match(r"\s*([-*+]|\d+[.)])\s", cur[0]))
        # every top-level list item is its own block, and a paragraph after a list starts a new one
        if not fence and cur and (top_item or (prev_item and not line.startswith((" ", "\t")))):
            blocks.append("\n".join(cur))
            cur = []
        cur.append(line)
    if cur:
        blocks.append("\n".join(cur))
    return blocks


def _pair_row(en: str, ko: str) -> str:
    return ('<div class="bi" markdown>\n<div class="bi-en" markdown>\n\n' + en.strip() +
            '\n\n</div>\n<div class="bi-ko" markdown>\n\n' + (ko.strip() or "&nbsp;") + "\n\n</div>\n</div>\n")


def _bilingual(en_md: str, ko_md: str) -> str:
    """Pair English and Korean paragraph by paragraph; mermaid diagrams are shown once, full width."""
    en_blocks = _blocks(en_md)
    ko_blocks = [b for b in _blocks(_MERMAID_RE.sub("", ko_md or "")) if b.strip()]
    out: list[str] = []
    ko_i = 0
    for b in en_blocks:
        if _MERMAID_RE.fullmatch(b.strip()):
            out.append(b + "\n")
            continue
        ko = ko_blocks[ko_i] if ko_i < len(ko_blocks) else ""
        ko_i += 1
        if b.startswith("#") and ko.startswith("#"):
            out.append(b.rstrip() + "\n")  # UI text stays English; only the body is translated
        else:
            out.append(_pair_row(b, ko))
    if ko_i < len(ko_blocks):  # Korean text longer than English: keep the rest
        out.append(_pair_row("", "\n\n".join(ko_blocks[ko_i:])))
    return "\n".join(out)


# --- hierarchy helpers -------------------------------------------------------

def venue_of(res: Resource) -> str:
    """Collection: the main venues stand alone; every other conference goes under Others."""
    return res.venue if res.venue in VENUE_ORDER else OTHERS


def group_of(res: Resource) -> str | None:
    """Second level: region for the main venues, the conference name inside Others."""
    return res.region if venue_of(res) != OTHERS else res.venue


def venue_slug(venue: str) -> str:
    return slugify(venue)


def region_slug(region: str) -> str:
    return slugify(region or "other")


def _venues(resources: list[Resource]) -> list[str]:
    present = {venue_of(r) for r in resources}
    ordered = [v for v in VENUE_ORDER if v in present]
    ordered += sorted(present - set(VENUE_ORDER) - {OTHERS})
    return ordered + ([OTHERS] if OTHERS in present else [])


def _regions(resources: list[Resource]) -> list[str]:
    present = {g for r in resources if (g := group_of(r))}
    return [g for g in REGION_ORDER if g in present] + sorted(present - set(REGION_ORDER))


def added_date(db: Database, res: Resource) -> str:
    """Date shown for a paper: first YouTube upload among its videos, else when it was archived."""
    dates = [l.video.published_at[:10] for l in db.videos_for(res.id) if l.video.published_at]
    return min(dates) if dates else (res.created_at or "")[:10]


def resource_rel_path(res: Resource) -> str:
    return f"papers/{res.id}-{slugify(res.title)}.md"


def _paper_row(r: Resource, db: Database, with_region: bool) -> str:
    n = len(db.videos_for(r.id))
    cells = [f"[{_cell(r.title)}](../{r.markdown_path or resource_rel_path(r)})"]
    if with_region:
        cells.append(group_of(r) or "-")
    cells += [r.category, ":material-youtube: " + str(n) if n else "-"]
    return "| " + " | ".join(cells) + " |"


# --- pages ---------------------------------------------------------------------

def render_resource(db: Database, res: Resource) -> str:
    """Write the canonical paper page and return its path relative to docs/."""
    videos = db.videos_for(res.id)
    rel = resource_rel_path(res)
    venue = venue_of(res)
    vs = venue_slug(venue)
    meta = {
        "id": res.id,
        "title": res.title,
        "date": added_date(db, res),
        "venue": venue,
        "region": res.region or None,
        "year": res.year,
        "category": res.category,
        "tags": res.tags,
        "source_type": res.source_type,
        "source_url": res.source_url,
        "authors": res.authors,
        "youtube_videos": [
            {"video_id": l.video.video_id, "url": l.video.video_url, "title": l.video.video_title,
             "timestamp": l.timestamp_note}
            for l in videos
        ],
    }
    crumbs = [f"[{venue}](../{vs}/index.md)"]
    if group := group_of(res):
        crumbs.append(f"[{group}](../{vs}/{region_slug(group)}.md)")
    if res.year:
        crumbs.append(f"[{res.year}](../{vs}/by-year.md#{res.year})")
    crumbs.append(f"[{res.category}](../{vs}/by-topic.md#{slugify(res.category)})")

    is_url = res.source_url.startswith(("http://", "https://"))
    source = (f"[:material-open-in-new: Original paper]({res.source_url}){{ .md-button .md-button--primary target=_blank }}"
              if is_url else f":material-file-pdf-box: Local file: `{res.source_url}`")
    where = " ".join(x for x in (venue, group_of(res), str(res.year or "")) if x)
    parts = [_frontmatter(meta), GENERATED_MARK, " › ".join(crumbs) + "\n", f"# {res.title}\n"]
    if res.figure_path and (config.DOCS_DIR / res.figure_path).exists():
        cap = _cell(res.figure_caption or "Representative figure")
        parts.append(f'<figure class="rep-fig" markdown>\n![{cap}](../{res.figure_path}){{ loading=lazy }}\n'
                     f"<figcaption>{cap} — from the original paper"
                     f"{' (' + _cell(res.authors.split(',')[0].split('(')[0].strip()) + ' et al.)' if res.authors else ''}"
                     "</figcaption>\n</figure>\n")
    parts += [
        source + "\n",
        "| | |\n|---|---|\n"
        f"| Authors | {_cell(res.authors or '-')} |\n| Venue | {where} |\n"
        f"| Topic | {res.category} |\n| Type | {res.source_type} |\n| ID | `{res.id}` |\n",
    ]
    if res.one_line_summary:
        parts.append("## Summary\n\n" + _pair_row(f"**{res.one_line_summary}**",
                                                         f"**{res.one_line_summary_ko}**" if res.one_line_summary_ko else ""))
    if res.key_insights:
        ko = res.key_insights_ko
        parts.append("## Key Insights\n\n" + "\n".join(
            _pair_row(f"- {x}", f"- {ko[i]}" if i < len(ko) else "") for i, x in enumerate(res.key_insights)))
    if res.detailed_summary:
        parts.append("## Detailed Summary\n\n" + _bilingual(res.detailed_summary, res.detailed_summary_ko))
    if videos:
        parts.append("## Videos\n\n" + "\n\n".join(
            _embed(l) + f" · [Video page](../videos/{l.video.video_id}.md)" for l in videos) + "\n")

    old = res.markdown_path
    _write(config.DOCS_DIR / rel, "\n".join(p for p in parts if p))
    if old and old != rel:
        _remove_generated(config.DOCS_DIR / old)
    if old != rel:
        db.set_markdown_path(res.id, rel)
    return rel


def render_video(db: Database, video_id: str) -> str | None:
    video = db.get_video(video_id)
    if video is None:
        return None
    links: list[ResourceLink] = db.resources_for(video_id)
    rel = f"videos/{video_id}.md"
    meta = {"title": video.video_title or video_id, "video_id": video_id, "video_url": video.video_url,
            "resources": [l.resource.id for l in links]}
    rows = [f"| [{_cell(l.resource.title)}](../{l.resource.markdown_path or resource_rel_path(l.resource)}) | "
            f"{l.resource.category} | {l.timestamp_note or '-'} |" for l in links]
    body = [
        _frontmatter(meta), GENERATED_MARK, f"\n# {video.video_title or video_id}\n",
        _embed(VideoLink(video=video)) + "\n",
        "## Papers in this video\n\n" + _table("| Paper | Topic | Note |", rows) if links else "",
    ]
    _write(config.DOCS_DIR / rel, "\n".join(p for p in body if p))
    return rel


def render_videos_index(db: Database) -> str:
    videos = db.list_videos()
    rows = [f"| [{_cell(v.video_title or v.video_id)}]({v.video_id}.md) | {len(db.resources_for(v.video_id))} | "
            f"[:material-youtube:]({v.video_url}) |" for v in videos]
    text = GENERATED_MARK + "\n\n# Videos\n\n" + (_table("| Video | Papers | YouTube |", rows) if videos
                                                  else "No videos yet.\n")
    _write(config.VIDEOS_DIR / "index.md", text)
    return "videos/index.md"


def _grouped(db: Database, items: list[Resource], key, order: list, with_region: bool) -> list[str]:
    head = "| Paper | Region / Conference | Topic | Videos |" if with_region else "| Paper | Topic | Videos |"
    groups: dict = defaultdict(list)
    for r in items:
        groups[key(r) if key(r) in order else "Other"].append(r)
    out = []
    for k in [*order, "Other"]:
        if groups.get(k):
            rows = [_paper_row(r, db, with_region) for r in sorted(groups[k], key=lambda r: r.title.lower())]
            out.append(f"## {k}\n\n" + _table(head, rows))
    return out


def render_venue(db: Database, venue: str, papers: list[Resource]) -> tuple[list[tuple[str, str]], list[str]]:
    """Write one venue's pages. Returns (sidebar entries, written paths)."""
    vs = venue_slug(venue)
    regions = _regions(papers)
    years = sorted({r.year for r in papers if r.year}, reverse=True)
    nav: list[tuple[str, str]] = []
    written = [f"{vs}/index.md", f"{vs}/by-year.md", f"{vs}/by-topic.md"]

    lines = [GENERATED_MARK, f"\n# {venue}\n",
             f"**{len(papers)}** papers · [By year](by-year.md) · [By topic](by-topic.md)\n"]
    if regions and years:
        count = Counter((group_of(r), r.year) for r in papers)
        rows = []
        for g in regions:
            cells = [f"[{c}]({region_slug(g)}.md#{y})" if (c := count[(g, y)]) else "" for y in years]
            rows.append(f"| [{g}]({region_slug(g)}.md) | " + " | ".join(cells) +
                        f" | {sum(1 for r in papers if group_of(r) == g)} |")
        label = "Conference" if venue == OTHERS else "Region"
        lines.append(f"## {label} × Year\n\n" + _table(f"| {label} | " + " | ".join(map(str, years)) + " | Total |", rows))
    by_cat = Counter(r.category for r in papers)
    lines.append("## Topics\n\n" + _table("| Topic | Papers |", [
        f"| [{c}](by-topic.md#{slugify(c)}) | {by_cat[c]} |" for c in CATEGORIES if by_cat[c]]))
    _write(config.DOCS_DIR / vs / "index.md", "\n".join(lines))

    for g in regions:
        items = [r for r in papers if group_of(r) == g]
        body = [GENERATED_MARK, f"\n# {g if venue == OTHERS else venue + ' ' + g}\n", f"**{len(items)}** papers\n"]
        body += _grouped(db, items, lambda r: r.year, years, with_region=False)
        path = f"{vs}/{region_slug(g)}.md"
        _write(config.DOCS_DIR / path, "\n".join(body))
        nav.append((g, path))
        written.append(path)

    body = [GENERATED_MARK, f"\n# {venue} by year\n"] + _grouped(db, papers, lambda r: r.year, years, True)
    _write(config.DOCS_DIR / vs / "by-year.md", "\n".join(body))
    body = [GENERATED_MARK, f"\n# {venue} by topic\n"] + _grouped(db, papers, lambda r: r.category,
                                                                   list(CATEGORIES), True)
    _write(config.DOCS_DIR / vs / "by-topic.md", "\n".join(body))
    nav += [("By Year", f"{vs}/by-year.md"), ("By Topic", f"{vs}/by-topic.md")]
    return nav, written


def render_index(db: Database, recent: int = 15) -> None:
    resources = db.list_resources()
    venues = _venues(resources)
    by_venue = Counter(venue_of(r) for r in resources)
    dated = sorted(((added_date(db, r), r) for r in resources), key=lambda x: x[0], reverse=True)
    recent_rows = [
        f"| {d} | [{_cell(r.title)}]({r.markdown_path or resource_rel_path(r)}) | "
        f"{venue_of(r)}{' ' + str(r.year) if r.year else ''} | {r.category} | "
        f"{':material-youtube: ' + str(n) if (n := len(db.videos_for(r.id))) else '-'} |"
        for d, r in dated[:recent]]
    lines = [
        GENERATED_MARK, "\n# YouTube - Paper Reading Archive\n",
        "A reading archive of technical papers, each summarized and linked to its reading video on the "
        "[Nemo Reading Archive](https://www.youtube.com/@99007nemo) YouTube channel.\n",
        f"**{len(resources)}** papers · **{len(db.list_videos())}** videos\n",
        "## Collections\n\n" + _table("| Collection | Papers |", [
            f"| [{v}]({venue_slug(v)}/index.md) | {by_venue[v]} |" for v in venues]) if venues else "",
        "## Recently added\n\n" + _table("| Date | Paper | Venue | Topic | Videos |", recent_rows)
        if resources else "No papers yet.\n",
    ]
    _write(config.DOCS_DIR / "index.md", "\n".join(l for l in lines if l))


def write_nav(nav: list) -> None:
    """Replace the generated nav block in mkdocs.yml."""
    path = config.ROOT / "mkdocs.yml"
    text = path.read_text(encoding="utf-8")
    block = NAV_BEGIN + "\n" + yaml.safe_dump({"nav": nav}, allow_unicode=True, sort_keys=False) + NAV_END
    if NAV_BEGIN in text and NAV_END in text:
        new = re.sub(re.escape(NAV_BEGIN) + r".*?" + re.escape(NAV_END), lambda _: block, text, flags=re.S)
    else:
        new = text.rstrip() + "\n\n" + block + "\n"
    if new != text:
        _write(path, new)


def _remove_generated(path: Path) -> None:
    """Delete a page only if it is inside docs/ and was generated by this tool."""
    try:
        path.resolve().relative_to(config.DOCS_DIR.resolve())
    except ValueError:
        return
    try:
        if path.is_file() and GENERATED_MARK in path.read_text(encoding="utf-8"):
            path.unlink()
            log.info("이전 페이지 삭제: %s", path.relative_to(config.DOCS_DIR))
    except OSError as e:
        log.warning("이전 페이지 삭제 실패: %s (%s)", path, e)


def _render_hubs(db: Database) -> set[str]:
    """Home, venue pages, videos index and nav. Returns the paths written."""
    resources = db.list_resources()
    written = {"index.md", render_videos_index(db)}
    nav: list = [{"Home": "index.md"}]
    for v in _venues(resources):
        sub, paths = render_venue(db, v, [r for r in resources if venue_of(r) == v])
        written.update(paths)
        nav.append({v: [f"{venue_slug(v)}/index.md"] + [{t: p} for t, p in sub]})
    nav += [{"Videos": "videos/index.md"}, {"Tags": "tags.md"}]
    render_index(db)
    write_nav(nav)
    return written


def refresh(db: Database, resource: Resource | None = None) -> None:
    """Re-render one resource (plus its videos) and the hub pages."""
    if resource is not None:
        render_resource(db, resource)
        for l in db.videos_for(resource.id):
            render_video(db, l.video.video_id)
    _render_hubs(db)


def rebuild_all(db: Database) -> int:
    resources = db.list_resources()
    keep = {render_resource(db, r) for r in resources}
    keep |= {p for v in db.list_videos() if (p := render_video(db, v.video_id))}
    keep |= _render_hubs(db)
    keep_abs = {(config.DOCS_DIR / p).resolve() for p in keep}
    for p in config.DOCS_DIR.rglob("*.md"):
        if p.resolve() not in keep_abs:
            _remove_generated(p)
    for d in sorted(config.DOCS_DIR.rglob("*"), reverse=True):  # drop folders left empty
        if d.is_dir() and not any(d.iterdir()):
            d.rmdir()
    return len(resources)
